pub const CELL_W: usize = 7;
pub const CELL_H: usize = 8;

/// The dots of a character's cell, 8 rows of 7 bits (bit 6 = the leftmost column). A
/// character outside `$20-$5F` is upper-cased, or shown as a blank.
pub fn glyph(c: char) -> [u8; CELL_H] {
    let c = c.to_ascii_uppercase();
    let mut cell = [0u8; CELL_H];
    if let Some((_, rows)) = GLYPHS.iter().find(|(g, _)| *g == c) {
        for (y, row) in rows.iter().enumerate() {
            for (x, dot) in row.bytes().enumerate() {
                if dot == b'#' {
                    cell[y] |= 1 << (5 - x);
                }
            }
        }
    }
    cell
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn glyphs_are_in_order_and_well_formed() {
        for (i, (c, rows)) in GLYPHS.iter().enumerate() {
            assert_eq!(*c as usize, 0x20 + i);
            assert!(rows
                .iter()
                .all(|r| r.len() == 5 && r.bytes().all(|b| b == b'#' || b == b'.')));
        }
    }

    #[test]
    fn dots_sit_in_columns_1_to_5() {
        assert_eq!(glyph('T')[0], 0b0111110);
        assert_eq!(glyph('a'), glyph('A'));
        assert_eq!(glyph('~'), [0; 8]);
    }
}
